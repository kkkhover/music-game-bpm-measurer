const dicts: Record<Language, Dict> = { zh, en, ja, ko, fr, de, es, ru, pt };

// 模块级当前语言（App 切换语言时调用 setLang + 触发重渲染）
let currentLang: Language = 'zh';

export function setLang(l: Language): void {
  currentLang = l;
}

export function getLang(): Language {
  return currentLang;
}

/** 翻译函数：t('key')；支持 {n} / {path} 占位符替换 */
export function t(key: string, vars?: Record<string, string | number>): string {
  let str = dicts[currentLang][key] ?? dicts.zh[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      str = str.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
    }
  }
  return str;
}
